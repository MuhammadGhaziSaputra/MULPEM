-- 1. TABEL SISWA
CREATE TABLE IF NOT EXISTS public.siswa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL,
    kelas TEXT NOT NULL,
    total_poin INTEGER DEFAULT 0,
    level_gamifikasi INTEGER DEFAULT 1,
    nama_level TEXT DEFAULT 'Pemula',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT uk_siswa_nama_kelas UNIQUE (nama, kelas)
);

-- 2. TABEL NILAI KUIS FORMATIF
CREATE TABLE IF NOT EXISTS public.nilai_kuis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    siswa_id BIGINT REFERENCES public.siswa(id) ON DELETE CASCADE,
    unit_id INTEGER NOT NULL,
    skor_kuis INTEGER NOT NULL,
    status_tuntas BOOLEAN DEFAULT false,
    poin_didapat INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT uk_nilai_siswa_unit UNIQUE (siswa_id, unit_id)
);

-- 3. TABEL REFLEKSI SISWA
CREATE TABLE IF NOT EXISTS public.refleksi_siswa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    siswa_id BIGINT REFERENCES public.siswa(id) ON DELETE CASCADE,
    unit_id INTEGER NOT NULL,
    pemahaman_skala INTEGER,
    bagian_sulit TEXT,
    strategi_belajar TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT uk_refleksi_siswa_unit UNIQUE (siswa_id, unit_id)
);

-- ========================================================
-- ATUR KEAMANAN ROW LEVEL SECURITY (RLS) AGAR BISA DIBACA & DITULIS OLEH WEB
-- ========================================================
ALTER TABLE public.siswa ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nilai_kuis ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.refleksi_siswa ENABLE ROW LEVEL SECURITY;

-- Kebijakan Akses Publik (Anonim) untuk Siswa & Guru
