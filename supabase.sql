CREATE POLICY "Allow anon insert siswa" ON public.siswa FOR INSERT TO anon WITH CHECK (true);
CREATE POLICY "Allow anon update siswa" ON public.siswa FOR UPDATE TO anon USING (true);

CREATE POLICY "Allow anon select nilai_kuis" ON public.nilai_kuis FOR SELECT TO anon USING (true);
CREATE POLICY "Allow anon insert nilai_kuis" ON public.nilai_kuis FOR INSERT TO anon WITH CHECK (true);
CREATE POLICY "Allow anon update nilai_kuis" ON public.nilai_kuis FOR UPDATE TO anon USING (true);

CREATE POLICY "Allow anon select refleksi" ON public.refleksi_siswa FOR SELECT TO anon USING (true);
CREATE POLICY "Allow anon insert refleksi" ON public.refleksi_siswa FOR INSERT TO anon WITH CHECK (true);
CREATE POLICY "Allow anon update refleksi" ON public.refleksi_siswa FOR UPDATE TO anon USING (true);

